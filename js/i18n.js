  var current = 'en';

  function has(lang) { return Object.prototype.hasOwnProperty.call(L, lang); }

  function setLang(lang) { if (has(lang)) current = lang; return current; }
  function getLang() { return current; }
  function list() {
    return Object.keys(L)
      .map(function (code) { return { code: code, name: L[code]._name }; })
      .sort(function (a, b) {
        if (a.code === 'en') return -1;      // the fallback leads
        if (b.code === 'en') return 1;
        return a.name.localeCompare(b.name);
      });
  }

  /* Closest locale the browser asks for, English when nothing matches. */
  function preferred(languages) {
    var wanted = languages || (typeof navigator !== 'undefined'
      ? (navigator.languages || [navigator.language]) : []);
    for (var i = 0; i < wanted.length; i++) {
      if (!wanted[i]) continue;
      var code = String(wanted[i]).toLowerCase();
      if (has(code)) return code;
      var base = code.split('-')[0];
      if (has(base)) return base;
    }
    return 'en';
  }

